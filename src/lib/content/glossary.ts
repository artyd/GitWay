type Matcher = { source: string; flags: string; lookup: Map<string, GlossaryEntry> };
let cached: Matcher | null = null;

const WORD = "0-9A-Za-zА-Яа-яЀ-ӿ'ʼ’\\-";

function escapeRe(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/**
 * Готує джерело регексу з усіх словоформ (довші — раніше) плюс словник форма→термін.
 * Повертаємо source/flags (а не готовий RegExp): кожен виклик пошуку створює
 * СВІЙ інстанс, бо регекс із прапорцем `g` є stateful (lastIndex) і його не можна
 * безпечно ділити між викликами.
 */
export function glossaryMatcher(): Matcher {
  if (cached) return cached;
  const lookup = new Map<string, GlossaryEntry>();
  const forms: string[] = [];
  for (const e of GLOSSARY) {
    for (const f of e.forms) {
      const key = f.toLowerCase();
      if (!lookup.has(key)) {
        lookup.set(key, e);
        forms.push(f);
      }
    }
  }
  forms.sort((a, b) => b.length - a.length);
  const body = forms.map(escapeRe).join("|");
  // Межі: перед формою й після неї не має бути «літери слова».
  const source = `(?<![${WORD}])(${body})(?![${WORD}])`;
  cached = { source, flags: "giu", lookup };
  return cached;
}

export type TermMatch = { start: number; end: number; text: string; entry: GlossaryEntry };

/**
 * Знаходить у тексті ЛИШЕ ПЕРШЕ входження кожного терміна (щоб не рябіло).
 * Повертає непересічні збіги, відсортовані за позицією.
 */
export function findTermMatches(text: string): TermMatch[] {
  const { source, flags, lookup } = glossaryMatcher();
  const regex = new RegExp(source, flags);
  const out: TermMatch[] = [];
  const seen = new Set<GlossaryEntry>();
  let m: RegExpExecArray | null;
  while ((m = regex.exec(text)) !== null) {
    if (m.index === regex.lastIndex) regex.lastIndex++; // страховка від зациклення
    const raw = m[1];
    const entry = lookup.get(raw.toLowerCase());
    if (entry && !seen.has(entry)) {
      seen.add(entry);
      out.push({ start: m.index, end: m.index + raw.length, text: raw, entry });
    }
  }
  return out;
}
